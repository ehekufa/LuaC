-- Self-contained UDP and TCP loopback example. No Internet access is needed.
local receiver = socket.udp()
assert(receiver:bind("127.0.0.1", 0))
local _, port = receiver:getsockname()
local sender = socket.udp()
sender:sendto("ping", "127.0.0.1", port)
local message, address = receiver:receivefrom(32)
print("UDP " .. address .. ": " .. message)
sender:close()
receiver:close()

local server = socket.bind("127.0.0.1", 0)
local _, tcpPort = server:getsockname()
local client = socket.connect("127.0.0.1", tcpPort)
client:send("hello")
local peer = server:accept()
print("TCP: " .. peer:receive(5))
peer:close()
client:close()
server:close()

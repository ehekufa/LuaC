local path = os.getenv('LUAC_FFI_FIXTURE')
assert(path and path ~= '', 'LUAC_FFI_FIXTURE must name the test shared library')
local library = assert(ffi.open(path))
assert(ffi.call(library, 'luac_test_add64', 'int64(int64,int64)', 4611686018427387904, 4611686018427387903) == math.maxinteger)
assert(ffi.call(library, 'luac_test_mul', 'double(double,double)', 2.5, 4) == 10)
assert(ffi.call(library, 'luac_test_length', 'size_t(string)', 'Привет') == 12)
assert(ffi.call(library, 'luac_test_abs', 'int32(int32)', -42) == 42)
assert(ffi.close(library))
print('LuaC FFI: OK')

local png=assert(engine.load_texture('tests/fixtures/pixel.png'))
assert(png.width==2 and png.height==1 and png.channels==4 and #png.pixels==8)
assert(string.byte(png.pixels,1)==255 and string.byte(png.pixels,4)==255)
local missing,missingError=engine.load_texture('tests/fixtures/missing.png')
assert(missing==nil and type(missingError)=='string')
local jpg,err=engine.load_texture('tests/fixtures/pixel.jpg')
assert(jpg and jpg.width==1 and jpg.height==1,err)
local world=engine.world()
local ball=engine.create(world,'Ball',0,0)
engine.set_sprite(ball,png,2,2)
assert(ball.texture==png and ball.width==2 and ball.height==2)
engine.set_body(ball,{restitution=0.5,friction=0.1,gravity_x=0,gravity_y=0})
local floor=engine.create(world,'Floor',0,6)
engine.set_size(floor,20,2)
engine.set_body(floor,{kinematic=true})
engine.set_gravity(world,0,10)
for i=1,120 do engine.update(world,1/60) end
assert(ball.y<=4.0001 and math.abs(ball.vy)<20)
engine.inject_key(world,'W',true)
assert(engine.is_key_down(world,'W') and engine.is_key_pressed(world,'W'))
engine.clear_input(world)
assert(not engine.is_key_down(world,'W'))
engine.inject_mouse(world,12,34,0,true)
local x,y=engine.mouse_pos(world)
assert(x==12 and y==34 and engine.is_mouse_down(world,0) and engine.is_mouse_clicked(world,0))
engine.inject_touch(world,7,50,60,true)
x,y=engine.touch_pos(world,7)
assert(x==50 and y==60)
engine.inject_touch(world,7,0,0,false)
assert(engine.touch_pos(world,7)==nil)
local text=engine.text(world,'Счёт: 42',10,20,18)
assert(world.overlay_text[text].text=='Счёт: 42')
engine.clear_text(world)
assert(#world.overlay_text==0)
print('LuaC game assets physics input: OK')

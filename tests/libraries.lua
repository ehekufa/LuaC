local function eq(actual, expected, message)
  if actual ~= expected then
    error((message or "eq") .. ": " .. tostring(actual) .. " ~= " .. tostring(expected))
  end
end

-- Text, encodings and URLs.
eq(text.trim("  hi\n"), "hi")
eq(text.replace("a-b-a", "a", "x"), "x-b-x")
local pieces = text.split("a,b,c", ",")
eq(#pieces, 3)
eq(text.join(pieces, "|"), "a|b|c")
eq(text.lpad("7", 3, "0"), "007")
eq(hex.encode("Lua"), "4c7561")
eq(hex.decode("4c7561"), "Lua")
eq(base64.encode("hello"), "aGVsbG8=")
eq(base64.decode("aGVsbG8="), "hello")
eq(url.encode("a b/"), "a%20b%2F")
eq(url.decode("a%20b%2F"), "a b/")
local parsed = url.parse("http://localhost:8080/a?q=1#x")
eq(parsed.host, "localhost")
eq(parsed.port, 8080)
eq(url.build(parsed), "http://localhost:8080/a?q=1#x")

-- JSON, checksums and cryptographic SHA-256/HMAC.
local value, decodeError = json.decode('{"name":"LuaC","items":[1,true,3],"unicode":"\\u041b"}')
eq(decodeError, nil)
eq(value.name, "LuaC")
eq(value.items[2], true)
eq(value.unicode, "Л")
eq(json.encode({1, 2, 3}), "[1,2,3]")
local invalid, invalidMessage = json.decode("{broken")
eq(invalid, nil)
assert(type(invalidMessage) == "string")
eq(hash.crc32("123456789"), 3421780262)
eq(hash.adler32("123456789"), 152961502)
eq(hash.sha256("abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad")
eq(hash.hmac_sha256("key", "The quick brown fox jumps over the lazy dog"),
   "f7bc83f430538424b13298e6aa6fb143ef4d59a14946175997479dbc2d1a3cd8")


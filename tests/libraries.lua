-- Real UDP and TCP loopback exchanges; no external network is needed.
eq(type(socket.tcp()), "userdata")
local udp = socket.udp()
assert(udp:bind("127.0.0.1", 0))
local ip, port = udp:getsockname()
eq(ip, "127.0.0.1")
assert(port > 0)
local sender = socket.udp()
eq(sender:sendto("ping", "127.0.0.1", port), 4)
local message, from, fromPort = udp:receivefrom(16)
eq(message, "ping")
eq(from, "127.0.0.1")
assert(fromPort > 0)
sender:close()
udp:close()

local server = socket.bind("127.0.0.1", 0)
local _, serverPort = server:getsockname()
local client = socket.connect("127.0.0.1", serverPort)
eq(client:send("hello"), 5)
local peer = server:accept()
eq(peer:receive(5), "hello")
eq(peer:send("ok"), 2)
eq(client:receive(2), "ok")
client:close()
peer:close()
server:close()
assert(#socket.addresses("localhost") > 0)
assert(#socket.gethostname() > 0)


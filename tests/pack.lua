local function hex(bytes)
  local s = ''
  for i = 1, #bytes do s = s .. string.format('%02x', string.byte(bytes, i)) end
  return s
end
local b = string.pack('<bB hH i4I4 i8I8', -128, 255, -1234, 54321, -123456, 345678, -1234567890, 987654321)
assert(hex(b) == '80ff2efb31d4c01dfeff4e4605002efd69b6ffffffffb168de3a00000000')
local a1,a2,a3,a4,a5,a6,a7,a8,pos = string.unpack('<bB hH i4I4 i8I8', b)
assert(a1 == -128 and a2 == 255 and a3 == -1234 and a4 == 54321)
assert(a5 == -123456 and a6 == 345678 and a7 == -1234567890 and a8 == 987654321 and pos == #b+1)
local text = 'a' .. string.char(0) .. 'b'
local s = string.pack('>s2c5z', text, 'xy', 'end')
local a,c,z,p = string.unpack('>s2c5z', s)
assert(a == text and c == 'xy' .. string.char(0,0,0) and z == 'end' and p == #s + 1)
local floats = string.pack('>fd', 1.5, -2.25)
local f,d,last = string.unpack('>fd', floats)
assert(f == 1.5 and d == -2.25 and last == 13)
assert(hex(string.pack('!4 b Xh i4', 7, 0x12345678)) == '0700000078563412' or hex(string.pack('!4 b Xh i4', 7, 0x12345678)) == '0700000012345678')
assert(string.packsize('!4 b Xh i4') == 8)
local raw = 'abc' .. string.pack('<I2', 258)
local n,endpos = string.unpack('<I2', raw, -2)
assert(n == 258 and endpos == 6)
assert(not pcall(string.packsize, 'z'))
assert(not pcall(string.packsize, 's2'))
assert(not pcall(string.pack, 'b', 128))
assert(not pcall(string.pack, 'B', -1))
assert(not pcall(string.pack, 'c1', 'abc'))
assert(not pcall(string.pack, 'z', text))
assert(not pcall(string.unpack, 'I4', 'abc'))
assert(not pcall(string.unpack, 'z', 'abc'))
assert(not pcall(string.pack, 'i0', 1))
assert(not pcall(string.packsize, '!4 i3'))
assert(not pcall(string.packsize, 'Xc4'))
local wide = string.pack('>i16', -2)
assert(#wide == 16 and string.unpack('>i16', wide) == -2)
assert(not pcall(string.unpack, '>I16', string.char(1) .. string.rep(string.char(0), 15)))
assert(string.pack('c0', '') == '')
assert(string.unpack('c0', '') == '')
assert(string.unpack('', 'abc', 4) == 4)
assert(string.unpack('', 'abc', 0) == 1)
assert(string.unpack('', 'abc', -4) == 1)
assert(not pcall(string.unpack, '', 'abc', 5))
assert(string.packsize('!8 b Xd') == 8)
assert(string.unpack('>i16', string.pack('>i16', -1)) == -1)
assert(string.unpack('<I16', string.pack('<I16', -1)) == -1)
assert(not pcall(string.pack, 's17', 'a'))
assert(not pcall(string.packsize, 'X'))
assert(not pcall(string.unpack, 's1', string.char(10) .. 'abc'))
print('LuaC binary pack: OK')

local url=assert(os.getenv('WS_URL'))
local ws,err=websocket.connect(url)
assert(ws,err)
assert(ws:settimeout(2))
assert(ws:send('Привет','text'))
local msg,kind=ws:receive()
assert(msg=='echo:Привет' and kind=='text',tostring(msg)..' '..tostring(kind))
assert(ws:send('abc'..string.char(0)..'xyz','binary'))
msg,kind=ws:receive()
assert(msg=='abc'..string.char(0)..'xyz' and kind=='binary')
assert(ws:ping('tick'))
msg,kind=ws:receive()
assert(msg=='fragment-message' and kind=='text')
assert(ws:close())
print('WebSocket client OK')

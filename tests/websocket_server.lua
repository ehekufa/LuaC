local port=assert(os.getenv('WS_PORT'))
local listener,err=websocket.listen('127.0.0.1',tonumber(port))
assert(listener,err)
local peer,err2=listener:accept()
assert(peer,err2)
assert(peer:settimeout(2))
local msg,kind=peer:receive()
assert(msg=='server-text' and kind=='text')
assert(peer:send('reply:'..msg,'text'))
msg,kind=peer:receive()
assert(msg=='a'..string.char(0)..'b' and kind=='binary')
assert(peer:send(msg,'binary'))
msg,kind=peer:receive()
assert(msg=='one-two' and kind=='text')
assert(peer:close())
assert(listener:close())
print('WebSocket server OK')
